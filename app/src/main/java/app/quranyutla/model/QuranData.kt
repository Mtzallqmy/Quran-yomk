    fun getSurahByNumber(number: Int): Surah? = surahs.find { it.number == number }
    fun searchSurahs(query: String): List<Surah> {
        val trimmed = query.trim()
        if (trimmed.isEmpty()) return surahs
        return surahs.filter {
            it.nameAr.contains(trimmed) ||
            it.nameEn.contains(trimmed, ignoreCase = true) ||
            it.number.toString() == trimmed
        }
